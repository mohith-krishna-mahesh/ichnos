from ichnos.ui.widgets.banner import ASCII_LOGO_LINES

LOGO_LINES: list[str] = ASCII_LOGO_LINES
LOGO_ROW: int = 8
LOGO_COL: int = 49


def hex_to_rgb(hex_str: str) -> tuple[int, int, int]:
    """Converts a 6-digit hex color string to an (R, G, B) tuple."""
    h = hex_str.lstrip("#")
    if len(h) != 6:
        return (17, 17, 17)
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def get_theme_colors(
    theme_name: str | None = None,
) -> tuple[tuple[int, int, int], tuple[int, int, int]]:
    """Resolves (background_rgb, logo_rgb) for a given or active theme."""
    from ichnos.ui.theme import discover_user_themes, get_active_theme_name

    target = theme_name or get_active_theme_name()
    all_themes = discover_user_themes()
    t = all_themes.get(target)
    if t is not None:
        bg = hex_to_rgb(t.surface)
        if target == "hacker":
            logo = (112, 165, 235)  # signature Ichnos blue
        else:
            logo = hex_to_rgb(t.primary)
        return bg, logo
    return (17, 17, 17), (112, 165, 235)


def build_mascot_ansi(
    state: str = "idle",
    theme_bg: tuple[int, int, int] | str | None = None,
    theme_logo: tuple[int, int, int] | str | None = None,
) -> str:
    """Constructs a 96-column x 24-line truecolor ANSI string with sub-pixel half-blocks."""
    if isinstance(theme_bg, str):
        theme_bg = hex_to_rgb(theme_bg)
    if isinstance(theme_logo, str):
        theme_logo = hex_to_rgb(theme_logo)

    if theme_bg is None or theme_logo is None:
        def_bg, def_logo = get_theme_colors()
        theme_bg = theme_bg or def_bg
        theme_logo = theme_logo or def_logo

    # 96 x 48 pixel grid
    grid: list[list[tuple[int, int, int] | None]] = [[None for _ in range(96)] for _ in range(48)]
    for (gx, gy), col in IDLE_PIXELS.items():
        grid[gy][gx] = col

    if state == "blink":
        for (gx, gy), col in BLINK_DIFF.items():
            grid[gy][gx] = col

    logo_h = len(LOGO_LINES)
    logo_w = len(LOGO_LINES[0])
    lines: list[str] = []

    for r in range(24):
        cells: list[tuple[tuple[int, int, int], tuple[int, int, int], str]] = []
        for c in range(96):
            if LOGO_ROW <= r < LOGO_ROW + logo_h and LOGO_COL <= c < LOGO_COL + logo_w:
                ch = LOGO_LINES[r - LOGO_ROW][c - LOGO_COL]
                if ch != " ":
                    cells.append((theme_logo, theme_bg, ch))
                else:
                    cells.append((theme_bg, theme_bg, " "))
            elif (r == 1 and c == 12) or (r == 2 and c == 94):
                cells.append(((200, 220, 245), theme_bg, "+"))
            else:
                top = grid[2 * r][c] or theme_bg
                bot = grid[2 * r + 1][c] or theme_bg
                if top == theme_bg and bot == theme_bg:
                    cells.append((theme_bg, theme_bg, " "))
                else:
                    cells.append((top, bot, "▀"))

        # Build ANSI line with color transitions
        line_out: list[str] = []
        cur_fg: tuple[int, int, int] | None = None
        cur_bg: tuple[int, int, int] | None = None

        for fg, bg, ch in cells:
            codes = ""
            if fg != cur_fg and ch != " ":
                codes += f"[38;2;{fg[0]};{fg[1]};{fg[2]}m"
                cur_fg = fg
            if bg != cur_bg:
                codes += f"[48;2;{bg[0]};{bg[1]};{bg[2]}m"
                cur_bg = bg
            line_out.append(codes + ch)

        line_out.append("[0m")
        lines.append("".join(line_out))

    newline = chr(10)
    return newline.join(lines)


@functools.lru_cache(maxsize=32)
def get_themed_ansi(state: str = "idle", theme_name: str | None = None) -> str:
    """Cached getter for themed ANSI mascot strings."""
    bg, logo = get_theme_colors(theme_name)
    return build_mascot_ansi(state=state, theme_bg=bg, theme_logo=logo)


